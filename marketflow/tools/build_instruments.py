#!/usr/bin/env python3
"""Builds app/src/main/assets/www/js/instruments-data.js from Groww's public instrument CSV.

Usage: python3 tools/build_instruments.py path/to/instrument.csv
(CSV: https://growwapi-assets.groww.in/instruments/instrument.csv)
"""
import csv, json, sys, datetime

src = sys.argv[1]
eq, idx, fno = [], [], {}
for r in csv.DictReader(open(src, encoding="utf-8")):
    if r["segment"] == "CASH" and r["exchange"] == "NSE" and r["instrument_type"] == "EQ" and r["series"] in ("EQ", "BE"):
        eq.append([r["trading_symbol"], r["name"].strip()])
    elif r["segment"] == "CASH" and r["instrument_type"] == "IDX" and r["trading_symbol"]:
        idx.append([r["trading_symbol"], r["name"].strip(), r["exchange"]])
    elif r["segment"] == "FNO" and r["instrument_type"] == "FUT" and r["exchange"] in ("NSE", "BSE"):
        u = r["underlying_symbol"]
        if u and u not in fno:
            fno[u] = [r["exchange"], int(float(r["lot_size"] or 0))]
eq.sort(); idx.sort()
out = {"generated": datetime.date.today().isoformat(), "eq": eq, "idx": idx, "fno": fno}
with open("app/src/main/assets/www/js/instruments-data.js", "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/build_instruments.py from Groww's public instrument list. */\n")
    f.write("window.MF_INSTRUMENTS = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n")
print(len(eq), "equities,", len(idx), "indices,", len(fno), "F&O underlyings")
